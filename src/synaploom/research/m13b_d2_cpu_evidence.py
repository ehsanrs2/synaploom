"""D2 review: real B256/B232 synthetic evaluation and exclusive tiny-CPU attempt records.

NEVER loads CIFAR, scientific seeds, protected evaluations or GPU. Synthetic
byte checks are NOT trustworthy independent scientific data attestation; file
creation with exclusive mode is NOT immutable/WORM or cryptographically signed.
"""
from __future__ import annotations

import hashlib
import json
import math
import os
from pathlib import Path
import re
from typing import Any, Mapping, Sequence

import torch
from torch import Tensor, nn

from synaploom.data.streams import TensorTask
from synaploom.training.evaluation import evaluate_task
from synaploom.research.m13b_d2_live_cpu_runner_probe import run_tiny_cpu_probe

KIND = "M13B_D2_SYNTHETIC_EVAL_AND_ATTEMPT_EVIDENCE_V1"
N = 1000
B = 256
SIZES = (256, 256, 256, 232)
ATTEMPT_ID = re.compile(r"[a-z][a-z0-9_-]{0,63}\Z")


def _json(value: Any) -> bytes:
    return json.dumps(value, sort_keys=True, separators=(",", ":"),
                      ensure_ascii=True, allow_nan=False).encode("ascii")


def _digest(t: Tensor) -> str:
    if not isinstance(t, Tensor) or t.device.type != "cpu":
        raise ValueError("research accepts only generated CPU tensors")
    x = t.detach().contiguous()
    h = hashlib.sha256(_json({"shape": list(x.shape), "dtype": str(x.dtype)}))
    h.update(b"\0")
    h.update(x.numpy().tobytes())
    return h.hexdigest()


def make_synthetic_reference_task() -> TensorTask:
    """1000 rows, two invented classes and a float32 integral sample ID."""
    y = torch.arange(N, dtype=torch.long) % 2
    x = torch.cat((torch.nn.functional.one_hot(y, 2).float(),
                   torch.arange(N, dtype=torch.float32).unsqueeze(1)), dim=1)
    return TensorTask(task_id=0, classes=(0, 1),
                      train_x=x[:8].clone(), train_y=y[:8].clone(),
                      eval_x=x, eval_y=y)


class _Observed(nn.Module):
    def __init__(self) -> None:
        super().__init__()
        self.events: list[dict[str, Any]] = []

    def forward(self, x: Tensor) -> Tensor:
        if x.device.type != "cpu" or x.ndim != 2 or x.shape[1] != 3:
            raise ValueError("unexpected synthetic evaluator input shape")
        ids = x[:, 2].to(torch.int64).tolist()
        self.events.append({"ids": ids, "sha256": _digest(x)})
        return x[:, :2] * 10


def audit_reference_cpu_evaluation(task: TensorTask | None = None) -> dict[str, Any]:
    """Observe actual evaluate_task forwards; independently compare generated bytes."""
    t = make_synthetic_reference_task() if task is None else task
    reference = make_synthetic_reference_task()
    if (not isinstance(t, TensorTask) or t.task_id != 0 or t.classes != (0, 1)):
        raise ValueError("not the reference synthetic task")
    digests: dict[str, str] = {}
    for field in ("train_x", "train_y", "eval_x", "eval_y"):
        actual, known = getattr(t, field), getattr(reference, field)
        digest = _digest(actual)
        if digest != _digest(known):
            raise ValueError(f"mismatched synthetic source bytes: {field}")
        digests[field] = digest
    observer = _Observed()
    result = evaluate_task(observer, t, batch_size=B, device="cpu",
                           allowed_classes=(0, 1))
    expected = [
        {"ids": list(range(i, min(i + B, N))),
         "sha256": _digest(t.eval_x[i:min(i + B, N)])}
        for i in range(0, N, B)
    ]
    if observer.events != expected:
        raise ValueError("real evaluator grouped incorrect ordered synthetic sample bytes")
    if result.examples != N or result.accuracy != 1.0 or not math.isfinite(result.loss):
        raise ValueError("real evaluator missed or misclassified synthetic examples")
    if tuple(len(x["ids"]) for x in observer.events) != SIZES:
        raise ValueError("B256/B232 real-evaluator tail mismatch")
    return {
        "kind": KIND, "status": "SYNTHETIC_REAL_EVAL_B256_B232_PASS",
        "synthetic_input_sha256": digests,
        "observed_forward_count": len(observer.events),
        "observed_batch_sizes": list(SIZES),
        "observed_input_sha256": [e["sha256"] for e in observer.events],
        "observed_first_last_ids": [[e["ids"][0], e["ids"][-1]]
                                   for e in observer.events],
        "all_1000_synthetic_rows_exactly_once": True,
        "protected_membership_attested": False,
        "science_executable": False, "gpu_used": False,
        "scientific_claim": "NONE",
    }


def _filename(attempt_id: str) -> str:
    if not isinstance(attempt_id, str) or not ATTEMPT_ID.fullmatch(attempt_id):
        raise ValueError("unsafe or missing synthetic attempt identifier")
    return attempt_id + ".json"


def write_synthetic_attempt(directory: str | Path, *, attempt_id: str,
                            fault_after_step: int | None = None) -> Path:
    """Write one real *tiny* CPU probe attempt, preserving injected failures."""
    name = _filename(attempt_id)
    if fault_after_step is not None and (
        type(fault_after_step) is not int or not 1 <= fault_after_step <= 12
    ):
        raise ValueError("invalid small-CPU-only injected failure step")
    folder = Path(directory)
    if folder.is_symlink():
        raise ValueError("no symlinked evidence directory")
    folder.mkdir(parents=True, exist_ok=True)
    destination = folder / name
    if destination.exists() or destination.is_symlink():
        raise FileExistsError(name)
    eval_record = audit_reference_cpu_evaluation()
    probe = run_tiny_cpu_probe(seed=13, masked=True, fault_after_step=fault_after_step)
    terminal = probe.get("status")
    if terminal not in ("ACTUAL_TINY_SYNTHETIC_CPU_RUNNER_PASS",
                        "SYNTHETIC_CPU_RUNNER_FAILURE_RETAINED"):
        raise ValueError("unrecognized CPU probe terminal state")
    if probe.get("science_executable") is not False or probe.get("gpu_used") is not False:
        raise ValueError("unexpected scientific execution flag")
    body = {
        "schema": 1, "kind": KIND, "attempt_id": attempt_id,
        "terminal_state": terminal,
        "reference_eval": eval_record, "tiny_cpu_probe": probe,
        "actual_science_optimizer_steps": 0,
        "protected_eval_accessed": False, "gpu_used": False,
        "science_executable": False, "scientific_claim": "NONE",
        "signed_or_worm": False,
    }
    packet = dict(body)
    packet["content_sha256"] = hashlib.sha256(_json(body)).hexdigest()
    # Exclusive creation guards against repeated attempt IDs; a crash leaves
    # an incomplete file that fails subsequent audit. fsync aids durability.
    with destination.open("xb") as out:
        out.write(_json(packet) + b"\n")
        out.flush()
        os.fsync(out.fileno())
    return destination


def verify_synthetic_attempts(directory: str | Path,
                              *, expected_ids: Sequence[str]) -> dict[str, Any]:
    """No omission or silent exclusion of failed toy attempts; not a signed log."""
    if not isinstance(expected_ids, (list, tuple)) or not expected_ids:
        raise ValueError("expected IDs required")
    names = [_filename(item) for item in expected_ids]
    if len(names) != len(set(names)):
        raise ValueError("duplicate expected attempt")
    folder = Path(directory)
    if not folder.is_dir() or folder.is_symlink():
        raise ValueError("missing/untrusted attempt directory")
    entries = list(folder.iterdir())
    if (len(entries) != len(names) or {p.name for p in entries} != set(names)
            or any(p.is_symlink() or not p.is_file() for p in entries)):
        raise ValueError("missing/extra or unsafe attempt evidence")
    summaries = []
    for attempt_id, name in zip(expected_ids, names):
        try:
            record = json.loads((folder / name).read_bytes())
        except (ValueError, UnicodeDecodeError) as exc:
            raise ValueError("incomplete or unreadable attempt JSON") from exc
        if not isinstance(record, dict) or record.get("attempt_id") != attempt_id:
            raise ValueError("wrong attempt identity")
        digest = record.get("content_sha256")
        body = {k: v for k, v in record.items() if k != "content_sha256"}
        if (not isinstance(digest, str)
                or hashlib.sha256(_json(body)).hexdigest() != digest):
            raise ValueError("attempt content digest mismatch")
        probe, eval_info = body.get("tiny_cpu_probe"), body.get("reference_eval")
        if not isinstance(probe, Mapping) or not isinstance(eval_info, Mapping):
            raise ValueError("missing runner or sample witness")
        if (body.get("kind") != KIND or body.get("signed_or_worm") is not False
                or body.get("scientific_claim") != "NONE"
                or body.get("science_executable") is not False
                or body.get("gpu_used") is not False
                or body.get("protected_eval_accessed") is not False
                or body.get("actual_science_optimizer_steps") != 0
                or eval_info.get("status") != "SYNTHETIC_REAL_EVAL_B256_B232_PASS"
                or eval_info.get("observed_batch_sizes") != list(SIZES)
                or eval_info.get("protected_membership_attested") is not False
                or probe.get("science_executable") is not False
                or probe.get("gpu_used") is not False):
            raise ValueError("unsafe CPU research evidence contract")
        status = probe.get("status")
        if status != body.get("terminal_state") or status not in (
            "ACTUAL_TINY_SYNTHETIC_CPU_RUNNER_PASS",
            "SYNTHETIC_CPU_RUNNER_FAILURE_RETAINED",
        ):
            raise ValueError("altered/missing terminal state")
        if status == "ACTUAL_TINY_SYNTHETIC_CPU_RUNNER_PASS":
            if probe.get("real_cpu_optimizer_post_step_observations") != 12:
                raise ValueError("incomplete success step witness")
        else:
            steps = probe.get("observed_cpu_post_step_calls_before_failure")
            if type(steps) is not int or not 0 <= steps <= 12:
                raise ValueError("malformed retained failure step count")
        summaries.append({"attempt_id": attempt_id, "terminal_state": status,
                          "content_sha256": digest})
    return {
        "kind": KIND, "status": "COMPLETE_SYNTHETIC_ATTEMPT_AUDIT",
        "attempt_count": len(summaries), "attempts": summaries,
        "all_successful": all(s["terminal_state"] ==
                              "ACTUAL_TINY_SYNTHETIC_CPU_RUNNER_PASS" for s in summaries),
        "signed_or_worm_attestation": False,
        "science_executable": False, "scientific_claim": "NONE",
    }
